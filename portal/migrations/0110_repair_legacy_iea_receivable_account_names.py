from django.db import migrations


MALFORMED_PREFIX = "Rider object ("


def repair_legacy_iea_receivable_accounts(apps, schema_editor):
    ReceivableAccount = apps.get_model("portal", "ReceivableAccount")
    SeasonMembership = apps.get_model("portal", "SeasonMembership")
    LegacyPersonLink = apps.get_model("portal", "LegacyPersonLink")

    accounts = (
        ReceivableAccount.objects
        .filter(
            finance_domain="iea",
            legacy_membership_id__isnull=False,
        )
        .order_by("id")
    )

    for account in accounts.iterator():
        try:
            membership = SeasonMembership.objects.select_related(
                "rider",
                "season",
            ).get(pk=account.legacy_membership_id)
        except SeasonMembership.DoesNotExist:
            continue

        rider = membership.rider

        # Historical models used inside migrations do not retain the live
        # Rider.__str__ implementation. Build the user-facing name explicitly.
        rider_name = " ".join(
            part.strip()
            for part in (rider.first_name, rider.last_name)
            if part and part.strip()
        )

        changed_fields = []

        # Repair only names known to have been generated by the broken v3.5
        # historical-model interpolation. Preserve manually edited names.
        if account.name.startswith(MALFORMED_PREFIX) and rider_name:
            account.name = (
                f"{rider_name} — {membership.season.name} — "
                f"IEA #{membership.id}"
            )
            changed_fields.append("name")

        # Restore the canonical People relationship where the v3.2 legacy
        # identity bridge can resolve this rider. Never overwrite an existing
        # primary person.
        if account.primary_person_id is None:
            link = (
                LegacyPersonLink.objects
                .filter(rider_id=rider.id)
                .select_related("person")
                .first()
            )
            if (
                link is not None
                and link.person_id is not None
                and link.person.team_id == account.team_id
            ):
                account.primary_person_id = link.person_id
                changed_fields.append("primary_person")

        if changed_fields:
            account.save(update_fields=changed_fields)


